-- V5: Notificaciones
-- Las alertas (stock bajo, vencimientos, fiados atrasados...) se calculan
-- al momento. Aqui solo se guarda cuales ya vio cada usuario, para que
-- "marcar como leida" funcione igual en la PC y en el celular.
-- NO editar este archivo una vez ejecutado. Los cambios van en V6, V7...
-- =====================================================================

CREATE TABLE notificaciones_leidas (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id  BIGINT       NOT NULL,
    clave       VARCHAR(150) NOT NULL,
    leida_en    TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT (NOW() AT TIME ZONE 'America/Lima'),
    CONSTRAINT fk_notificaciones_leidas_usuario FOREIGN KEY (usuario_id) REFERENCES usuarios (id),
    CONSTRAINT uk_notificaciones_leidas UNIQUE (usuario_id, clave)
);
