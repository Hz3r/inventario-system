-- =====================================================================
-- V2: módulos del POS
--   presentaciones (unidad / media caja / caja), venta por peso (KG),
--   proveedores, clientes, caja, ventas con pago mixto, kardex,
--   compras a proveedores, gastos, fiados y abonos.
-- NO editar este archivo una vez ejecutado. Los cambios van en V3, V4...
--
-- Reglas del diseño:
--   * El stock se guarda SIEMPRE en la unidad base del producto (UND, KG o LT).
--   * El stock solo cambia junto con un movimiento en movimientos_inventario.
--   * Dinero en NUMERIC(10,2); cantidades en NUMERIC(12,3) (permite 0.250 kg).
--   * Las ventas guardan el precio y el costo del momento.
--   * Fechas en hora de Perú (America/Lima).
-- =====================================================================


-- ---------------------------------------------------------------------
-- 1. Ajustes a tablas existentes
-- ---------------------------------------------------------------------

-- Productos: unidad base UND / KG / LT (CAJA pasa a ser una presentación)
ALTER TABLE productos DROP CONSTRAINT ck_productos_unidad_medida;
UPDATE productos SET unidad_medida = 'KG'  WHERE unidad_medida = 'Kg';
UPDATE productos SET unidad_medida = 'UND' WHERE unidad_medida = 'CAJA' OR unidad_medida IS NULL;
ALTER TABLE productos
    ALTER COLUMN unidad_medida SET DEFAULT 'UND',
    ALTER COLUMN unidad_medida SET NOT NULL,
    ADD CONSTRAINT ck_productos_unidad_medida CHECK (unidad_medida IN ('UND', 'KG', 'LT'));

-- Productos: stock en decimales (para kilos) y nombre correcto
ALTER TABLE productos RENAME COLUMN stock_inicial TO stock_actual;
ALTER TABLE productos
    ALTER COLUMN stock_actual DROP DEFAULT,
    ALTER COLUMN stock_actual TYPE NUMERIC(12,3) USING COALESCE(stock_actual, 0),
    ALTER COLUMN stock_actual SET DEFAULT 0,
    ALTER COLUMN stock_actual SET NOT NULL,
    ALTER COLUMN stock_minimo TYPE NUMERIC(12,3) USING COALESCE(stock_minimo, 0),
    ALTER COLUMN stock_minimo SET DEFAULT 0,
    ALTER COLUMN precio_costo TYPE NUMERIC(10,2),
    ALTER COLUMN precio_venta TYPE NUMERIC(10,2),
    ALTER COLUMN vencimiento  TYPE DATE USING vencimiento::date;

-- Productos: código de barras único (varios NULL sí se permiten), activo
ALTER TABLE productos
    ADD CONSTRAINT uk_productos_codigo_barras UNIQUE (codigo_barras),
    ADD COLUMN activo BOOLEAN NOT NULL DEFAULT TRUE;

CREATE INDEX ix_productos_nombre ON productos (lower(nombre));

-- Usuarios: nombre y rol (por ahora solo ADMIN; CAJERO queda para cuando crezca)
ALTER TABLE usuarios
    ADD COLUMN nombre VARCHAR(100),
    ADD COLUMN rol    VARCHAR(20) NOT NULL DEFAULT 'ADMIN',
    ADD COLUMN activo BOOLEAN     NOT NULL DEFAULT TRUE,
    ADD CONSTRAINT ck_usuarios_rol CHECK (rol IN ('ADMIN', 'CAJERO'));

-- Perfil de la tienda: logo como BYTEA (OID da problemas) + datos del ticket
ALTER TABLE perfil_tienda DROP COLUMN logo;
ALTER TABLE perfil_tienda
    ADD COLUMN logo           BYTEA,
    ADD COLUMN telefono       VARCHAR(20),
    ADD COLUMN mensaje_ticket VARCHAR(255);


-- ---------------------------------------------------------------------
-- 2. Proveedores
-- ---------------------------------------------------------------------
CREATE TABLE proveedores (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre     VARCHAR(150) NOT NULL,
    ruc        VARCHAR(11),
    contacto   VARCHAR(100),
    telefono   VARCHAR(20),
    email      VARCHAR(150),
    direccion  VARCHAR(255),
    activo     BOOLEAN   NOT NULL DEFAULT TRUE,
    creado_en  TIMESTAMP NOT NULL DEFAULT (now() AT TIME ZONE 'America/Lima'),
    CONSTRAINT uk_proveedores_ruc UNIQUE (ruc)
);

-- Proveedor habitual del producto (opcional)
ALTER TABLE productos
    ADD COLUMN proveedor_id BIGINT,
    ADD CONSTRAINT fk_productos_proveedor FOREIGN KEY (proveedor_id) REFERENCES proveedores (id);


-- ---------------------------------------------------------------------
-- 3. Presentaciones: unidad / media caja / caja / six pack ...
--    factor = cuántas unidades base trae (caja de 12 -> 12)
--    La unidad base es el propio producto (factor 1), no se repite aquí.
-- ---------------------------------------------------------------------
CREATE TABLE producto_presentaciones (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    producto_id    BIGINT        NOT NULL,
    nombre         VARCHAR(50)   NOT NULL,          -- "Media caja", "Caja x12"
    factor         NUMERIC(12,3) NOT NULL,
    precio_venta   NUMERIC(10,2) NOT NULL,
    codigo_barras  VARCHAR(255),
    activo         BOOLEAN       NOT NULL DEFAULT TRUE,
    CONSTRAINT fk_presentaciones_producto FOREIGN KEY (producto_id) REFERENCES productos (id) ON DELETE CASCADE,
    CONSTRAINT uk_presentaciones_codigo_barras UNIQUE (codigo_barras),
    CONSTRAINT uk_presentaciones_producto_nombre UNIQUE (producto_id, nombre),
    CONSTRAINT ck_presentaciones_factor CHECK (factor > 0),
    CONSTRAINT ck_presentaciones_precio CHECK (precio_venta >= 0)
);


-- ---------------------------------------------------------------------
-- 4. Clientes (para fiados)
-- ---------------------------------------------------------------------
CREATE TABLE clientes (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre          VARCHAR(150) NOT NULL,
    dni             VARCHAR(8),
    telefono        VARCHAR(20),
    direccion       VARCHAR(255),
    limite_credito  NUMERIC(10,2),                   -- NULL = sin límite
    nota            VARCHAR(255),
    activo          BOOLEAN   NOT NULL DEFAULT TRUE,
    creado_en       TIMESTAMP NOT NULL DEFAULT (now() AT TIME ZONE 'America/Lima'),
    CONSTRAINT uk_clientes_dni UNIQUE (dni)
);


-- ---------------------------------------------------------------------
-- 5. Caja (apertura y cierre del día)
-- ---------------------------------------------------------------------
CREATE TABLE cajas (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id      BIGINT        NOT NULL,
    abierta_en      TIMESTAMP     NOT NULL DEFAULT (now() AT TIME ZONE 'America/Lima'),
    cerrada_en      TIMESTAMP,
    monto_inicial   NUMERIC(10,2) NOT NULL DEFAULT 0,  -- sencillo con el que se abre
    monto_esperado  NUMERIC(10,2),                     -- efectivo que debería haber al cerrar
    monto_contado   NUMERIC(10,2),                     -- efectivo contado al cerrar
    diferencia      NUMERIC(10,2),                     -- contado - esperado
    estado          VARCHAR(10)   NOT NULL DEFAULT 'ABIERTA',
    nota            VARCHAR(255),
    CONSTRAINT fk_cajas_usuario FOREIGN KEY (usuario_id) REFERENCES usuarios (id),
    CONSTRAINT ck_cajas_estado CHECK (estado IN ('ABIERTA', 'CERRADA'))
);

-- Solo puede haber una caja abierta a la vez
CREATE UNIQUE INDEX ux_cajas_una_abierta ON cajas (estado) WHERE estado = 'ABIERTA';


-- ---------------------------------------------------------------------
-- 6. Ventas
-- ---------------------------------------------------------------------
CREATE SEQUENCE ventas_numero_seq START WITH 1;

CREATE TABLE ventas (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    numero             BIGINT        NOT NULL DEFAULT nextval('ventas_numero_seq'),  -- N° de ticket
    fecha              TIMESTAMP     NOT NULL DEFAULT (now() AT TIME ZONE 'America/Lima'),
    caja_id            BIGINT        NOT NULL,
    usuario_id         BIGINT        NOT NULL,
    cliente_id         BIGINT,                         -- obligatorio si hay parte fiada
    subtotal           NUMERIC(10,2) NOT NULL,
    descuento          NUMERIC(10,2) NOT NULL DEFAULT 0,
    total              NUMERIC(10,2) NOT NULL,
    efectivo_recibido  NUMERIC(10,2),                  -- con cuánto pagó en efectivo
    vuelto             NUMERIC(10,2),
    estado             VARCHAR(12)   NOT NULL DEFAULT 'COMPLETADA',
    anulada_en         TIMESTAMP,
    motivo_anulacion   VARCHAR(255),
    nota               VARCHAR(255),
    CONSTRAINT uk_ventas_numero UNIQUE (numero),
    CONSTRAINT fk_ventas_caja    FOREIGN KEY (caja_id)    REFERENCES cajas (id),
    CONSTRAINT fk_ventas_usuario FOREIGN KEY (usuario_id) REFERENCES usuarios (id),
    CONSTRAINT fk_ventas_cliente FOREIGN KEY (cliente_id) REFERENCES clientes (id),
    CONSTRAINT ck_ventas_estado CHECK (estado IN ('COMPLETADA', 'ANULADA')),
    CONSTRAINT ck_ventas_montos CHECK (subtotal >= 0 AND descuento >= 0 AND total >= 0)
);

ALTER SEQUENCE ventas_numero_seq OWNED BY ventas.numero;
CREATE INDEX ix_ventas_fecha ON ventas (fecha);
CREATE INDEX ix_ventas_caja  ON ventas (caja_id);

-- Detalle: qué se vendió. cantidad está en la presentación vendida;
-- cantidad_base = cantidad * factor es lo que se descuenta del stock.
CREATE TABLE venta_detalle (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    venta_id         BIGINT        NOT NULL,
    producto_id      BIGINT        NOT NULL,
    presentacion_id  BIGINT,                           -- NULL = unidad base
    descripcion      VARCHAR(255)  NOT NULL,           -- nombre tal como salió en el ticket
    cantidad         NUMERIC(12,3) NOT NULL,
    factor           NUMERIC(12,3) NOT NULL DEFAULT 1,
    cantidad_base    NUMERIC(12,3) NOT NULL,
    precio_unitario  NUMERIC(10,2) NOT NULL,           -- precio de la presentación en ese momento
    costo_unitario   NUMERIC(10,2) NOT NULL DEFAULT 0, -- costo por unidad base en ese momento
    descuento        NUMERIC(10,2) NOT NULL DEFAULT 0,
    subtotal         NUMERIC(10,2) NOT NULL,
    CONSTRAINT fk_venta_detalle_venta        FOREIGN KEY (venta_id)        REFERENCES ventas (id) ON DELETE CASCADE,
    CONSTRAINT fk_venta_detalle_producto     FOREIGN KEY (producto_id)     REFERENCES productos (id),
    CONSTRAINT fk_venta_detalle_presentacion FOREIGN KEY (presentacion_id) REFERENCES producto_presentaciones (id),
    CONSTRAINT ck_venta_detalle_cantidad CHECK (cantidad > 0 AND factor > 0 AND cantidad_base > 0)
);

CREATE INDEX ix_venta_detalle_venta    ON venta_detalle (venta_id);
CREATE INDEX ix_venta_detalle_producto ON venta_detalle (producto_id);

-- Pagos de la venta: permite pago mixto (efectivo + Yape + fiado ...)
CREATE TABLE venta_pagos (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    venta_id    BIGINT        NOT NULL,
    metodo      VARCHAR(15)   NOT NULL,
    monto       NUMERIC(10,2) NOT NULL,
    referencia  VARCHAR(50),                          -- N° de operación Yape/Plin/tarjeta
    CONSTRAINT fk_venta_pagos_venta FOREIGN KEY (venta_id) REFERENCES ventas (id) ON DELETE CASCADE,
    CONSTRAINT ck_venta_pagos_metodo CHECK (metodo IN ('EFECTIVO', 'YAPE', 'PLIN', 'TARJETA', 'TRANSFERENCIA', 'FIADO')),
    CONSTRAINT ck_venta_pagos_monto  CHECK (monto > 0)
);

CREATE INDEX ix_venta_pagos_venta ON venta_pagos (venta_id);


-- ---------------------------------------------------------------------
-- 7. Compras / pedidos a proveedores
-- ---------------------------------------------------------------------
CREATE TABLE compras (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    proveedor_id     BIGINT        NOT NULL,
    usuario_id       BIGINT,
    fecha_pedido     TIMESTAMP     NOT NULL DEFAULT (now() AT TIME ZONE 'America/Lima'),
    fecha_recepcion  TIMESTAMP,                       -- al recibir, entra el stock
    estado           VARCHAR(10)   NOT NULL DEFAULT 'PEDIDO',
    total            NUMERIC(10,2) NOT NULL DEFAULT 0,
    metodo_pago      VARCHAR(15),
    nota             VARCHAR(255),
    CONSTRAINT fk_compras_proveedor FOREIGN KEY (proveedor_id) REFERENCES proveedores (id),
    CONSTRAINT fk_compras_usuario   FOREIGN KEY (usuario_id)   REFERENCES usuarios (id),
    CONSTRAINT ck_compras_estado CHECK (estado IN ('PEDIDO', 'RECIBIDO', 'CANCELADO')),
    CONSTRAINT ck_compras_metodo CHECK (metodo_pago IS NULL OR metodo_pago IN ('EFECTIVO', 'YAPE', 'PLIN', 'TARJETA', 'TRANSFERENCIA', 'CREDITO'))
);

CREATE INDEX ix_compras_proveedor ON compras (proveedor_id);

CREATE TABLE compra_detalle (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    compra_id        BIGINT        NOT NULL,
    producto_id      BIGINT        NOT NULL,
    presentacion_id  BIGINT,                           -- ej. se compró por cajas
    cantidad         NUMERIC(12,3) NOT NULL,
    factor           NUMERIC(12,3) NOT NULL DEFAULT 1,
    cantidad_base    NUMERIC(12,3) NOT NULL,
    costo_unitario   NUMERIC(10,2) NOT NULL,           -- costo de la presentación comprada
    subtotal         NUMERIC(10,2) NOT NULL,
    CONSTRAINT fk_compra_detalle_compra       FOREIGN KEY (compra_id)       REFERENCES compras (id) ON DELETE CASCADE,
    CONSTRAINT fk_compra_detalle_producto     FOREIGN KEY (producto_id)     REFERENCES productos (id),
    CONSTRAINT fk_compra_detalle_presentacion FOREIGN KEY (presentacion_id) REFERENCES producto_presentaciones (id),
    CONSTRAINT ck_compra_detalle_cantidad CHECK (cantidad > 0 AND factor > 0 AND cantidad_base > 0)
);

CREATE INDEX ix_compra_detalle_compra ON compra_detalle (compra_id);


-- ---------------------------------------------------------------------
-- 8. Kardex: movimientos de inventario
--    cantidad con signo: + entra, - sale (siempre en unidad base)
-- ---------------------------------------------------------------------
CREATE TABLE movimientos_inventario (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    producto_id       BIGINT        NOT NULL,
    fecha             TIMESTAMP     NOT NULL DEFAULT (now() AT TIME ZONE 'America/Lima'),
    motivo            VARCHAR(20)   NOT NULL,
    cantidad          NUMERIC(12,3) NOT NULL,
    stock_anterior    NUMERIC(12,3) NOT NULL,
    stock_resultante  NUMERIC(12,3) NOT NULL,
    costo_unitario    NUMERIC(10,2),
    venta_id          BIGINT,
    compra_id         BIGINT,
    usuario_id        BIGINT,
    nota              VARCHAR(255),
    CONSTRAINT fk_movimientos_producto FOREIGN KEY (producto_id) REFERENCES productos (id),
    CONSTRAINT fk_movimientos_venta    FOREIGN KEY (venta_id)    REFERENCES ventas (id),
    CONSTRAINT fk_movimientos_compra   FOREIGN KEY (compra_id)   REFERENCES compras (id),
    CONSTRAINT fk_movimientos_usuario  FOREIGN KEY (usuario_id)  REFERENCES usuarios (id),
    CONSTRAINT ck_movimientos_motivo CHECK (motivo IN
        ('INICIAL', 'VENTA', 'ANULACION_VENTA', 'COMPRA', 'AJUSTE_ENTRADA', 'AJUSTE_SALIDA', 'MERMA', 'DEVOLUCION')),
    CONSTRAINT ck_movimientos_cantidad CHECK (cantidad <> 0),
    CONSTRAINT ck_movimientos_saldo CHECK (stock_resultante = stock_anterior + cantidad)
);

CREATE INDEX ix_movimientos_producto_fecha ON movimientos_inventario (producto_id, fecha);


-- ---------------------------------------------------------------------
-- 9. Gastos
-- ---------------------------------------------------------------------
CREATE TABLE gastos (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha        TIMESTAMP     NOT NULL DEFAULT (now() AT TIME ZONE 'America/Lima'),
    categoria    VARCHAR(20)   NOT NULL,
    descripcion  VARCHAR(255),
    monto        NUMERIC(10,2) NOT NULL,
    metodo_pago  VARCHAR(15)   NOT NULL DEFAULT 'EFECTIVO',
    caja_id      BIGINT,                              -- si salió de la caja del día
    usuario_id   BIGINT,
    CONSTRAINT fk_gastos_caja    FOREIGN KEY (caja_id)    REFERENCES cajas (id),
    CONSTRAINT fk_gastos_usuario FOREIGN KEY (usuario_id) REFERENCES usuarios (id),
    CONSTRAINT ck_gastos_categoria CHECK (categoria IN
        ('SERVICIOS', 'ALQUILER', 'TRANSPORTE', 'SUELDOS', 'IMPUESTOS', 'MANTENIMIENTO', 'OTROS')),
    CONSTRAINT ck_gastos_metodo CHECK (metodo_pago IN ('EFECTIVO', 'YAPE', 'PLIN', 'TARJETA', 'TRANSFERENCIA')),
    CONSTRAINT ck_gastos_monto  CHECK (monto > 0)
);

CREATE INDEX ix_gastos_fecha ON gastos (fecha);


-- ---------------------------------------------------------------------
-- 10. Fiados y abonos
--     Un fiado nace de la parte FIADO de una venta (o se registra a mano
--     para deudas antiguas, con venta_id NULL).
-- ---------------------------------------------------------------------
CREATE TABLE fiados (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cliente_id   BIGINT        NOT NULL,
    venta_id     BIGINT,
    fecha        TIMESTAMP     NOT NULL DEFAULT (now() AT TIME ZONE 'America/Lima'),
    monto_total  NUMERIC(10,2) NOT NULL,
    saldo        NUMERIC(10,2) NOT NULL,
    estado       VARCHAR(10)   NOT NULL DEFAULT 'PENDIENTE',
    nota         VARCHAR(255),
    CONSTRAINT fk_fiados_cliente FOREIGN KEY (cliente_id) REFERENCES clientes (id),
    CONSTRAINT fk_fiados_venta   FOREIGN KEY (venta_id)   REFERENCES ventas (id),
    CONSTRAINT uk_fiados_venta   UNIQUE (venta_id),
    CONSTRAINT ck_fiados_estado  CHECK (estado IN ('PENDIENTE', 'PARCIAL', 'PAGADO', 'ANULADO')),
    CONSTRAINT ck_fiados_montos  CHECK (monto_total > 0 AND saldo >= 0 AND saldo <= monto_total)
);

CREATE INDEX ix_fiados_cliente ON fiados (cliente_id);
CREATE INDEX ix_fiados_pendientes ON fiados (cliente_id) WHERE estado IN ('PENDIENTE', 'PARCIAL');

CREATE TABLE abonos (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fiado_id    BIGINT        NOT NULL,
    fecha       TIMESTAMP     NOT NULL DEFAULT (now() AT TIME ZONE 'America/Lima'),
    monto       NUMERIC(10,2) NOT NULL,
    metodo      VARCHAR(15)   NOT NULL,
    referencia  VARCHAR(50),
    caja_id     BIGINT,
    usuario_id  BIGINT,
    CONSTRAINT fk_abonos_fiado   FOREIGN KEY (fiado_id)   REFERENCES fiados (id),
    CONSTRAINT fk_abonos_caja    FOREIGN KEY (caja_id)    REFERENCES cajas (id),
    CONSTRAINT fk_abonos_usuario FOREIGN KEY (usuario_id) REFERENCES usuarios (id),
    CONSTRAINT ck_abonos_metodo CHECK (metodo IN ('EFECTIVO', 'YAPE', 'PLIN', 'TARJETA', 'TRANSFERENCIA')),
    CONSTRAINT ck_abonos_monto  CHECK (monto > 0)
);

CREATE INDEX ix_abonos_fiado ON abonos (fiado_id);
