-- ---------- Categorías ----------
CREATE TABLE categorias (
    id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre  VARCHAR(255) NOT NULL,
    CONSTRAINT uk_categorias_nombre UNIQUE (nombre)
);

-- ---------- Perfil de la tienda ----------
CREATE TABLE perfil_tienda (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    direccion  VARCHAR(255),
    logo       OID,
    nombre     VARCHAR(255),
    ruc        VARCHAR(255)
);

-- ---------- Productos ----------
CREATE TABLE productos (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo_barras  VARCHAR(255),
    igv            BOOLEAN,
    imagenurl      VARCHAR(255),
    nombre         VARCHAR(255) NOT NULL,
    precio_costo   NUMERIC(38,2),
    precio_venta   NUMERIC(38,2),
    stock_inicial  INTEGER DEFAULT 0,
    stock_minimo   INTEGER,
    unidad_medida  VARCHAR(255),
    vencimiento    TIMESTAMP(6) WITHOUT TIME ZONE,
    categoria_id   BIGINT,
    CONSTRAINT ck_productos_unidad_medida
        CHECK (unidad_medida IN ('Kg', 'LT', 'CAJA', 'UND')),
    CONSTRAINT fk_productos_categoria
        FOREIGN KEY (categoria_id) REFERENCES categorias (id)
);

-- ---------- Usuarios ----------
CREATE TABLE usuarios (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email     VARCHAR(255) NOT NULL,
    password  VARCHAR(255) NOT NULL,
    CONSTRAINT uk_usuarios_email UNIQUE (email)
);
